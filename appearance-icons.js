function wardrobeAppearanceIcon(item,selectedGender=paperDollState.selectedGender) {
    if(!item||!['face','hair','beard'].includes(item.slot))return null;
    const source=WARDROBE_APPEARANCE_ICONS[selectedGender]?.[item.id==='hair-none'?'@native':item.id];
    return source||null;
}
function wardrobeAppearanceCategoryIcon(slot) {
    const kind=slot==='appearance'?'face':slot;
    if(!['face','hair','beard'].includes(kind))return null;
    const selected=selectedPaperDollItem(kind);
    const id=(selected?.id==='hair-none'?null:selected?.id)||(kind==='face'?'@native':kind==='hair'?'hair-classic-short':'beard-06');
    return wardrobeAppearanceIcon({slot:kind,id})||wardrobeAppearanceIcon({slot:kind,id:kind==='face'?'@native':'hair-classic-short'});
}
