"""Keep Pages below its 1 GB limit without deleting source/review evidence.

Publish runtime trees in full, plus every review page, document, and the gallery
resources they load. Machine-only captures/sources remain in Git, outside Pages.
Run with --write after adding a gallery; --check detects a stale publication list.
"""
import argparse
import json
import posixpath
import re
import subprocess
from html.parser import HTMLParser
from pathlib import Path
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
TEXT = {'.html', '.md', '.css', '.js', '.mjs'}
QUOTED_FILE = re.compile(r'''(?:["'`(])([A-Za-z0-9_./ -]+\.(?:webp|png|jpe?g|svg|css|js|mjs|jsonl?|html|md|woff2?|zip|gz|pdf|txt))(?:[?#][^\s"'`)]*)?["'`)]''')
DIRECTORY = re.compile(r'''["'`]([A-Za-z0-9_./-]+/)["'`]''')


class WebLinks(HTMLParser):
    def __init__(self):
        super().__init__()
        self.urls = []

    def handle_starttag(self, tag, attrs):
        self.urls.extend(value for key, value in attrs if key in {'href', 'src', 'poster'} and value)


def plan():
    paths = subprocess.check_output(['git', 'ls-files'], cwd=ROOT, text=True).splitlines()
    known = set(paths)
    # Runtime resources include dynamically constructed avatar/weapon paths.
    keep = {p for p in paths if not p.startswith(('review/', 'tests/', 'tools/', '.github/', 'docs/'))}
    seeds = {p for p in paths if Path(p).suffix in {'.html', '.md'} and not p.startswith(('tests/', 'tools/', '.github/'))}
    keep |= seeds
    queue, scanned = list(seeds), set()

    def add(path):
        if path in known:
            keep.add(path)
            if Path(path).suffix in TEXT and path not in scanned:
                queue.append(path)

    while queue:
        path = queue.pop()
        if path in scanned:
            continue
        scanned.add(path)
        try:
            source = (ROOT/path).read_text()
        except (OSError, UnicodeError):
            continue
        parent = posixpath.dirname(path)
        # Markdown inline code mentions many machine-only capture directories;
        # actual document links/images, rather than those mentions, are public.
        refs = re.findall(r'\]\(<?([^\s)>]+)', source) if Path(path).suffix == '.md' else QUOTED_FILE.findall(source)
        if Path(path).suffix == '.html':
            links = WebLinks()
            links.feed(source)
            refs += links.urls
        if Path(path).suffix == '.css':
            refs += re.findall(r'''url\(\s*["']?([^\)"']+)''', source)
        for raw in refs:
            url = urlsplit(raw)
            if url.scheme or url.netloc:
                continue
            raw = unquote(url.path)
            add(posixpath.normpath(posixpath.join(parent, raw)))
            add(raw)
        # Galleries also assemble URLs from directory prefixes and record IDs.
        if Path(path).suffix != '.md':
            for prefix in DIRECTORY.findall(source):
                directory = posixpath.normpath(posixpath.join(parent, prefix))+'/'
                for candidate in paths:
                    if candidate.startswith(directory):
                        add(candidate)
    omitted = sorted(p for p in paths if p.startswith('review/') and p not in keep)
    size = sum((ROOT/p).stat().st_size for p in keep if (ROOT/p).is_file())
    return keep, omitted, size


def config(omitted):
    excluded = ['tests', 'tools', '.github'] + omitted
    return ('# Generated by tools/prepare-pages.py --write. Source files remain in Git.\n'
            '# Runtime trees and linked webgallery resources are published unchanged.\n'
            'exclude:\n' + ''.join('  - '+json.dumps(p)+'\n' for p in excluded))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    kept, omitted, size = plan()
    target = ROOT/'_config.yml'
    expected = config(omitted)
    if args.write:
        target.write_text(expected)
    if args.check and (not target.is_file() or target.read_text() != expected):
        raise SystemExit('Pages list is stale: run python tools/prepare-pages.py --write')
    if size >= 1_000_000_000:
        raise SystemExit(f'Pages exceeds the 1 GB publication budget: {size} bytes')
    print(json.dumps({'publishedBytesBeforeCompression': size, 'publishedFiles': len(kept), 'machineOnlyFilesRetainedInGit': len(omitted)}))
